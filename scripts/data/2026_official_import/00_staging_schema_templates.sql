-- GZLY 2026 官方数据 staging 表模板
-- 目的：只创建 staging 表，不写正式表，不打开正式推荐。
-- 使用前必须确认官方 source_file/source_url/raw_text，不允许 fake/mock 2026 数据。

CREATE TABLE IF NOT EXISTS stg_gz_2026_score_segment (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  import_batch_id VARCHAR(120) NOT NULL,
  year SMALLINT NOT NULL,
  province VARCHAR(20) NOT NULL DEFAULT '贵州',
  subject_type VARCHAR(20) NOT NULL,
  score SMALLINT NOT NULL,
  score_label VARCHAR(40) NOT NULL DEFAULT '',
  segment_count INT NOT NULL DEFAULT 0,
  cumulative_count INT NOT NULL DEFAULT 0,
  cumulative_rate DECIMAL(8,4) DEFAULT NULL,
  rank_low INT NOT NULL,
  rank_high INT NOT NULL,
  source_name VARCHAR(120) NOT NULL DEFAULT '',
  source_url VARCHAR(500) NOT NULL,
  source_page_url VARCHAR(500) NOT NULL DEFAULT '',
  source_file VARCHAR(240) NOT NULL,
  raw_text TEXT NOT NULL,
  parse_method VARCHAR(80) NOT NULL DEFAULT '',
  review_required TINYINT NOT NULL DEFAULT 0,
  review_flags VARCHAR(500) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uk_stg_gz_2026_score_segment (import_batch_id, year, subject_type, score),
  KEY idx_stg_gz_2026_score_segment_batch (import_batch_id),
  KEY idx_stg_gz_2026_score_segment_rank (year, subject_type, rank_low, rank_high)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

